import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { chromium } from 'playwright';
const server = spawn(process.execPath, ['node_modules/vite/bin/vite.js', '--port', '1449', '--host', '127.0.0.1'], { stdio: 'pipe' });
let browser;
try {
  await new Promise((resolve, reject) => { const timer = setTimeout(() => reject(new Error('Vite startup timeout')), 20000); server.stdout.on('data', d => { if (String(d).includes('Local:')) { clearTimeout(timer); resolve(); } }); server.on('exit', code => { clearTimeout(timer); reject(new Error(`Vite exited ${code}`)); }); });
  try { browser = await chromium.launch(); } catch { browser = await chromium.launch({ channel: 'chrome' }); }
  const page = await browser.newPage({ viewport: { width: 1380, height: 960 } });
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://127.0.0.1:1449');
  await page.getByRole('heading', { name: 'Gedanken, die etwas bewegen.' }).waitFor();
  const nextBefore = await page.locator('.block').nth(1).boundingBox();
  await page.getByRole('heading', { name: 'Gedanken, die etwas bewegen.' }).click();
  const nextAfter = await page.locator('.block').nth(1).boundingBox();
  assert.ok(Math.abs(nextAfter.y - nextBefore.y) < 1, 'heading activation preserves layout');
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('button', { name: 'Python ausführen', exact: true }).count(), 1);
  await page.getByRole('button', { name: 'Python ausführen', exact: true }).click();
  await page.getByLabel('Codeausgabe').waitFor();
  assert.match(await page.getByLabel('Codeausgabe').innerText(), /Desktop-App/);
  assert.equal(await page.getByText('Nicht gestartet', { exact: true }).count(), 1);
  await page.getByRole('button', { name: /Aktivität/ }).click();
  assert.match(await page.getByRole('complementary', { name: 'Ausführungen' }).innerText(), /Nicht gestartet/);
  await page.getByRole('button', { name: 'Aktivität schließen' }).click();
  await page.getByRole('button', { name: 'Source', exact: true }).click();
  const markdown = await page.locator('.source-full').inputValue();
  assert.match(markdown, /```python/);
  assert.ok(!markdown.includes('Nicht gestartet'), 'execution output never modifies the Markdown');
  await page.getByRole('button', { name: 'Live', exact: true }).click();
  await page.getByRole('button', { name: /Neue Notiz/ }).click();
  await page.getByRole('button', { name: /Ausführbares Runbook/ }).click();
  await page.getByRole('heading', { name: 'Mein Runbook' }).waitFor();
  assert.equal(await page.getByRole('button', { name: /ausführen$/ }).count(), 2);
  await page.getByRole('button', { name: 'Source', exact: true }).click();
  const runbook = await page.locator('.source-full').inputValue();
  assert.match(runbook, /confirm: true/); assert.match(runbook, /PROJECT: THE-Note/);
  await page.locator('.source-full').fill(runbook.replace('# Mein Runbook', '# Mein bearbeitetes Runbook'));
  await page.getByRole('button', { name: 'Live', exact: true }).click();
  await page.getByRole('heading', { name: 'Mein bearbeitetes Runbook' }).waitFor();
  const tabs = page.getByRole('tablist', { name: 'Open documents' }).getByRole('tab');
  await tabs.first().click();
  await page.getByRole('heading', { name: 'Gedanken, die etwas bewegen.' }).waitFor();
  await tabs.last().click();
  await page.getByRole('heading', { name: 'Mein bearbeitetes Runbook' }).waitFor();
  await page.getByRole('button', { name: 'Farbschema wechseln' }).click();
  assert.equal(await page.locator('.app').getAttribute('data-theme'), 'forest');
  await page.getByRole('button', { name: 'Farbschema wechseln' }).click();
  const downloadWait = page.waitForEvent('download');
  page.once('dialog', d => d.accept('Runbook.md'));
  await page.getByRole('button', { name: /Speichern/ }).click();
  const download = await downloadWait;
  assert.match(download.suggestedFilename(), /\.md$/);
  await page.getByRole('button', { name: /Neue Notiz/ }).click();
  await page.getByRole('button', { name: /Eine Idee skizzieren/ }).click();
  await page.locator('.mermaid-block svg').waitFor({ timeout: 20000 });
  assert.equal(await page.getByRole('button', { name: /ausführen$/ }).count(), 0, 'diagram is not executable');
  await page.setViewportSize({ width: 900, height: 740 });
  assert.ok(await page.locator('body').evaluate(el => el.scrollWidth <= innerWidth), 'no horizontal app overflow');
  assert.deepEqual(errors, []);
  console.log('PASS notebook: templates, code actions, browser boundary, activity, Markdown integrity, tabs, edits, themes, export, Mermaid, responsive layout.');
} finally { await browser?.close(); server.kill('SIGTERM'); }
