import { readFileSync, writeFileSync } from 'node:fs';
const d = JSON.parse(readFileSync('distribution.json', 'utf8'));
if (!/^\d+\.\d+\.\d+$/.test(d.version) || !/^[a-f0-9]{64}$/.test(d.sha256) || !/^[\w.-]+$/.test(d.asset) || d.repository !== 'tobwil/THENote') throw new Error('Invalid release metadata');
if (!/^[\w.-]+\.dmg$/.test(d.dmg?.asset) || !/^[a-f0-9]{64}$/.test(d.dmg?.sha256)) throw new Error('Invalid DMG metadata');
const url = `https://github.com/${d.repository}/releases/download/v${d.version}/${d.asset}`;
const notarized = d.notarized === true;
const signingNotice = notarized
  ? 'This is a preview for Apple Silicon, Developer ID signed and Apple-notarized.'
  : 'This is a preview for Apple Silicon, ad-hoc signed and not Apple-notarized.';
const release = `# BEGIN RELEASE (generated by scripts/sync-distribution.mjs)\nVERSION='${d.version}'\nARCHIVE='${d.asset}'\nSHA256='${d.sha256}'\nDOWNLOAD='${url}'\nNOTARIZED='${notarized}'\nSIGNING_NOTICE='${signingNotice}'\n# END RELEASE`;
const installer = readFileSync('install.sh', 'utf8').replace(/# BEGIN RELEASE[^]*?# END RELEASE/, release);
const cask = `cask "the-note" do
  version "${d.version}"
  sha256 "${d.sha256}"

  url "https://github.com/${d.repository}/releases/download/v#{version}/${d.asset}"
  name "THE Note"
  desc "Local Markdown notebook with executable code cells and inline AI"
  homepage "${d.site}"

  livecheck do
    skip "Preview releases are updated after verification"
  end

  depends_on arch: :arm64
  depends_on macos: :big_sur

  app "THE Note.app"

  caveats <<~EOS
    ${signingNotice}
${notarized ? '' : '    If macOS blocks opening, review THE Note in System Settings > Privacy & Security.\n'}    Save your notes and quit THE Note before upgrading. Note files are not removed.
  EOS
end
`;
const check = process.argv.includes('--check');
for (const [path, content] of [['install.sh', installer], ['Casks/the-note.rb', cask]]) {
  if (check) { if (readFileSync(path, 'utf8') !== content) throw new Error(`${path} is out of sync`); }
  else writeFileSync(path, content);
}
console.log(check ? 'Installer and cask match release metadata.' : 'Installer and cask updated.');
